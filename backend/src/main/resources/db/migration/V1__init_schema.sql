-- AMAN platform schema (PostgreSQL 14+). All timestamps are stored in UTC.

CREATE TABLE users (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    phone                VARCHAR(16)  NOT NULL UNIQUE,
    password_hash        VARCHAR(100) NOT NULL,
    role                 VARCHAR(20)  NOT NULL
        CHECK (role IN ('PATIENT', 'DOCTOR', 'CLINIC_ADMIN', 'SUPER_ADMIN')),
    phone_verified       BOOLEAN      NOT NULL DEFAULT FALSE,
    enabled              BOOLEAN      NOT NULL DEFAULT TRUE,
    consent_accepted_at  TIMESTAMP WITH TIME ZONE,
    created_at           TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE patients (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id      BIGINT       NOT NULL UNIQUE REFERENCES users (id) ON DELETE CASCADE,
    full_name    VARCHAR(200) NOT NULL,
    email        VARCHAR(200),
    birth_date   DATE,
    gender       VARCHAR(10),
    blood_type   VARCHAR(20),
    city         VARCHAR(100),
    avatar_seed  INTEGER      NOT NULL DEFAULT 0
);

CREATE TABLE specialties (
    id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code     VARCHAR(40)  NOT NULL UNIQUE,
    name_ru  VARCHAR(255) NOT NULL,
    name_en  VARCHAR(255) NOT NULL,
    name_kk  VARCHAR(255) NOT NULL
);

CREATE TABLE clinics (
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name                   VARCHAR(200)     NOT NULL,
    city                   VARCHAR(100)     NOT NULL,
    address                VARCHAR(300)     NOT NULL,
    latitude               DOUBLE PRECISION NOT NULL CHECK (latitude BETWEEN -90 AND 90),
    longitude              DOUBLE PRECISION NOT NULL CHECK (longitude BETWEEN -180 AND 180),
    phone                  VARCHAR(32)      NOT NULL,
    rating                 DOUBLE PRECISION NOT NULL CHECK (rating BETWEEN 0 AND 5),
    reviews_count          INTEGER          NOT NULL DEFAULT 0,
    working_hours          TEXT,
    image_seed             INTEGER          NOT NULL DEFAULT 0,
    change_deadline_hours  INTEGER          NOT NULL DEFAULT 2 CHECK (change_deadline_hours >= 0),
    demo                   BOOLEAN          NOT NULL DEFAULT FALSE
);
CREATE INDEX idx_clinics_city ON clinics (city);

CREATE TABLE clinic_services (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    clinic_id  BIGINT  NOT NULL REFERENCES clinics (id) ON DELETE CASCADE,
    name       TEXT,
    price_kzt  INTEGER NOT NULL CHECK (price_kzt >= 0)
);
CREATE INDEX idx_clinic_services_clinic ON clinic_services (clinic_id);

CREATE TABLE doctors (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name         VARCHAR(200)     NOT NULL,
    specialty_id      BIGINT           NOT NULL REFERENCES specialties (id),
    clinic_id         BIGINT           NOT NULL REFERENCES clinics (id),
    experience_years  INTEGER          NOT NULL CHECK (experience_years >= 0),
    rating            DOUBLE PRECISION NOT NULL CHECK (rating BETWEEN 0 AND 5),
    reviews_count     INTEGER          NOT NULL DEFAULT 0,
    price_kzt         INTEGER          NOT NULL CHECK (price_kzt >= 0),
    education         TEXT,
    qualification     TEXT,
    about             TEXT,
    languages         VARCHAR(20)      NOT NULL,
    avatar_seed       INTEGER          NOT NULL DEFAULT 0,
    female            BOOLEAN          NOT NULL DEFAULT FALSE,
    photo_url         VARCHAR(500)
);
CREATE INDEX idx_doctors_specialty ON doctors (specialty_id);
CREATE INDEX idx_doctors_clinic ON doctors (clinic_id);

CREATE TABLE doctor_services (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    doctor_id  BIGINT  NOT NULL REFERENCES doctors (id) ON DELETE CASCADE,
    name       TEXT,
    price_kzt  INTEGER NOT NULL CHECK (price_kzt >= 0)
);
CREATE INDEX idx_doctor_services_doctor ON doctor_services (doctor_id);

CREATE TABLE doctor_schedules (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    doctor_id          BIGINT  NOT NULL REFERENCES doctors (id) ON DELETE CASCADE,
    weekday            INTEGER NOT NULL CHECK (weekday BETWEEN 1 AND 7),
    start_minute       INTEGER NOT NULL CHECK (start_minute BETWEEN 0 AND 1439),
    end_minute         INTEGER NOT NULL CHECK (end_minute BETWEEN 1 AND 1440),
    slot_minutes       INTEGER NOT NULL CHECK (slot_minutes BETWEEN 5 AND 240),
    break_start_minute INTEGER,
    break_end_minute   INTEGER,
    CONSTRAINT uq_schedule_doctor_weekday UNIQUE (doctor_id, weekday),
    CONSTRAINT ck_schedule_range CHECK (end_minute > start_minute),
    CONSTRAINT ck_schedule_break CHECK (
        (break_start_minute IS NULL AND break_end_minute IS NULL)
        OR (break_start_minute IS NOT NULL AND break_end_minute > break_start_minute))
);

CREATE TABLE appointments (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    number            VARCHAR(32) NOT NULL UNIQUE,
    patient_id        BIGINT      NOT NULL REFERENCES patients (id) ON DELETE CASCADE,
    doctor_id         BIGINT      NOT NULL REFERENCES doctors (id),
    clinic_id         BIGINT      NOT NULL REFERENCES clinics (id),
    start_at          TIMESTAMP WITH TIME ZONE NOT NULL,
    duration_minutes  INTEGER     NOT NULL CHECK (duration_minutes > 0),
    status            VARCHAR(20) NOT NULL CHECK (status IN ('CONFIRMED', 'COMPLETED', 'CANCELLED')),
    reason            VARCHAR(300),
    price_kzt         INTEGER     NOT NULL CHECK (price_kzt >= 0),
    created_at        TIMESTAMP WITH TIME ZONE NOT NULL,
    rescheduled_count INTEGER     NOT NULL DEFAULT 0,
    cancel_reason     VARCHAR(300),
    review_rating     INTEGER CHECK (review_rating BETWEEN 1 AND 5),
    -- "doctorId:epochSecond" while active, NULL when cancelled. The unique
    -- constraint makes double booking impossible even under concurrency.
    active_slot_key   VARCHAR(64) UNIQUE,
    CONSTRAINT ck_active_slot CHECK (
        (status = 'CANCELLED' AND active_slot_key IS NULL)
        OR (status <> 'CANCELLED' AND active_slot_key IS NOT NULL))
);
CREATE INDEX idx_appt_patient_start ON appointments (patient_id, start_at);
CREATE INDEX idx_appt_doctor_start ON appointments (doctor_id, start_at);

CREATE TABLE reviews (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    appointment_id  BIGINT  NOT NULL UNIQUE REFERENCES appointments (id) ON DELETE CASCADE,
    doctor_id       BIGINT  NOT NULL REFERENCES doctors (id),
    patient_id      BIGINT  NOT NULL REFERENCES patients (id) ON DELETE CASCADE,
    rating          INTEGER NOT NULL CHECK (rating BETWEEN 1 AND 5),
    text            VARCHAR(1000),
    created_at      TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_reviews_doctor ON reviews (doctor_id);

CREATE TABLE lab_results (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_id   BIGINT       NOT NULL REFERENCES patients (id) ON DELETE CASCADE,
    test_code    VARCHAR(60)  NOT NULL,
    category     VARCHAR(30)  NOT NULL,
    name         TEXT,
    result_date  DATE         NOT NULL,
    laboratory   VARCHAR(200) NOT NULL,
    status       VARCHAR(20)  NOT NULL CHECK (status IN ('PENDING', 'PROCESSING', 'READY', 'ATTENTION')),
    document_id  BIGINT
);
CREATE INDEX idx_lab_patient_date ON lab_results (patient_id, result_date);

CREATE TABLE lab_indicators (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    result_id  BIGINT           NOT NULL REFERENCES lab_results (id) ON DELETE CASCADE,
    name       TEXT,
    value      DOUBLE PRECISION NOT NULL,
    unit       VARCHAR(30)      NOT NULL,
    ref_min    DOUBLE PRECISION,
    ref_max    DOUBLE PRECISION
);
CREATE INDEX idx_lab_indicators_result ON lab_indicators (result_id);

CREATE TABLE lab_orders (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_id   BIGINT       NOT NULL REFERENCES patients (id) ON DELETE CASCADE,
    name         TEXT,
    category     VARCHAR(30)  NOT NULL,
    doctor_name  VARCHAR(200) NOT NULL,
    order_date   DATE         NOT NULL,
    status       VARCHAR(20)  NOT NULL
);
CREATE INDEX idx_lab_orders_patient ON lab_orders (patient_id);

CREATE TABLE medical_record_entries (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_id   BIGINT      NOT NULL REFERENCES patients (id) ON DELETE CASCADE,
    type         VARCHAR(30) NOT NULL,
    entry_date   DATE        NOT NULL,
    title        TEXT,
    details      TEXT,
    doctor_name  VARCHAR(200),
    source_ref   VARCHAR(64) NOT NULL
);
CREATE INDEX idx_record_patient_date ON medical_record_entries (patient_id, entry_date);

CREATE TABLE medical_documents (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_id            BIGINT       NOT NULL REFERENCES patients (id) ON DELETE CASCADE,
    title                 VARCHAR(200) NOT NULL,
    kind                  VARCHAR(30)  NOT NULL,
    file_name             VARCHAR(255) NOT NULL,
    mime_type             VARCHAR(100) NOT NULL,
    size_bytes            BIGINT       NOT NULL CHECK (size_bytes > 0 AND size_bytes <= 10485760),
    storage_key           VARCHAR(64)  NOT NULL,
    sha256                VARCHAR(64)  NOT NULL,
    uploaded_at           TIMESTAMP WITH TIME ZONE NOT NULL,
    uploaded_by_patient   BOOLEAN      NOT NULL
);
CREATE INDEX idx_documents_patient ON medical_documents (patient_id);

CREATE TABLE notifications (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_id  BIGINT      NOT NULL REFERENCES patients (id) ON DELETE CASCADE,
    type        VARCHAR(40) NOT NULL,
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    is_read     BOOLEAN     NOT NULL DEFAULT FALSE,
    params_json TEXT,
    route       VARCHAR(200)
);
CREATE INDEX idx_notifications_patient ON notifications (patient_id, created_at);

CREATE TABLE favorite_doctors (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_id  BIGINT NOT NULL REFERENCES patients (id) ON DELETE CASCADE,
    doctor_id   BIGINT NOT NULL REFERENCES doctors (id) ON DELETE CASCADE,
    CONSTRAINT uq_favorite UNIQUE (patient_id, doctor_id)
);

CREATE TABLE otp_codes (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    phone       VARCHAR(16) NOT NULL,
    code_hash   VARCHAR(64) NOT NULL,
    expires_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    attempts    INTEGER     NOT NULL DEFAULT 0,
    consumed    BOOLEAN     NOT NULL DEFAULT FALSE
);
CREATE INDEX idx_otp_phone ON otp_codes (phone);

CREATE TABLE refresh_tokens (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    token_hash  VARCHAR(64) NOT NULL UNIQUE,
    expires_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    revoked     BOOLEAN     NOT NULL DEFAULT FALSE
);

-- Access audit for medical data. Stores WHO accessed WHAT; never the content.
CREATE TABLE audit_log (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id        BIGINT,
    action         VARCHAR(40) NOT NULL,
    resource_type  VARCHAR(40) NOT NULL,
    resource_id    VARCHAR(64),
    at             TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_audit_user_at ON audit_log (user_id, at);

